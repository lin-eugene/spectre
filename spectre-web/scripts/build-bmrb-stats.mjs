// Builds src/lib/structure/bmrb-stats.ts from data/raw/bmrb_aa_full.csv, the BMRB's public
// chemical shift statistics per residue type and atom
// (https://bmrb.io/ftp/pub/bmrb/statistics/chem_shifts/aa_full.csv): mean and standard deviation
// of every atom with at least 10 observations.
// Run: node scripts/build-bmrb-stats.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const rows = fs.readFileSync(path.join(root, "data/raw/bmrb_aa_full.csv"), "utf8").trim().split(/\r?\n/);
const head = rows.shift().split(",");
const col = (name) => head.indexOf(name);
const stats = {};
for (const line of rows) {
  const t = line.split(",");
  const count = Number(t[col("count")]);
  const avg = Number(t[col("avg")]);
  const std = Number(t[col("std")]);
  if (!(count >= 10) || !Number.isFinite(avg) || !Number.isFinite(std)) continue;
  (stats[t[col("comp_id")]] ??= {})[t[col("atom_id")]] = [avg, std];
}
const body = Object.entries(stats)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([resn, atoms]) => `  ${resn}: { ${Object.entries(atoms).map(([a, [m, s]]) => `${/^[A-Z0-9]+$/.test(a) ? a : JSON.stringify(a)}: [${m}, ${s}]`).join(", ")} },`)
  .join("\n");
const out = `// Generated by scripts/build-bmrb-stats.mjs from data/raw/bmrb_aa_full.csv (BMRB chemical shift
// statistics): [mean, standard deviation] in ppm per residue type and BMRB atom name.
export const BMRB_STATS: Record<string, Record<string, [number, number]>> = {
${body}
};
`;
fs.writeFileSync(path.join(root, "src/lib/structure/bmrb-stats.ts"), out);
console.log(`${Object.keys(stats).length} residue types`);
